static double te_call(const char *name, const double *a) {
  if (!strcmp(name, "erfinv")) return te_erfinv(a[0]);
  if (!strcmp(name, "digamma")) return te_digamma(a[0]);
  if (!strcmp(name, "beta")) return te_beta(a[0], a[1]);
  if (!strcmp(name, "gammainc_p")) return te_gammainc_p(a[0], a[1]);
  if (!strcmp(name, "betainc")) return te_betainc(a[0], a[1], a[2]);
  if (!strcmp(name, "zeta")) return te_zeta(a[0]);
  if (!strcmp(name, "lambertw")) return te_lambert_w(a[0]);
  if (!strcmp(name, "ei")) return te_ei(a[0]);
  if (!strcmp(name, "e1")) return te_e1(a[0]);
  if (!strcmp(name, "si")) return te_si(a[0]);
  if (!strcmp(name, "ci")) return te_ci(a[0]);
  if (!strcmp(name, "airy_ai")) return te_airy_ai(a[0]);
  if (!strcmp(name, "airy_bi")) return te_airy_bi(a[0]);
  if (!strcmp(name, "ellipk")) return te_ellip_k(a[0]);
  if (!strcmp(name, "ellipe")) return te_ellip_e(a[0]);
  if (!strcmp(name, "jacobi_sn")) return te_jacobi_sn(a[0], a[1]);
  if (!strcmp(name, "jacobi_cn")) return te_jacobi_cn(a[0], a[1]);
  if (!strcmp(name, "jacobi_dn")) return te_jacobi_dn(a[0], a[1]);
  if (!strcmp(name, "sph_bessel_j")) return te_sph_bessel_j(a[0], a[1]);
  if (!strcmp(name, "sph_bessel_y")) return te_sph_bessel_y(a[0], a[1]);
  if (!strcmp(name, "legendre_p")) return te_legendre_p(a[0], a[1]);
  if (!strcmp(name, "chebyshev_t")) return te_chebyshev_t(a[0], a[1]);
  if (!strcmp(name, "chebyshev_u")) return te_chebyshev_u(a[0], a[1]);
  if (!strcmp(name, "hermite_h")) return te_hermite_h(a[0], a[1]);
  if (!strcmp(name, "laguerre_l")) return te_laguerre_l(a[0], a[1]);
  if (!strcmp(name, "erf")) return te_erf(a[0]);
  if (!strcmp(name, "erfc")) return te_erfc(a[0]);
  return NAN;
}

int main(void) {
  int failures = 0;
  unsigned long i;
  for (i = 0; i < sizeof(cases) / sizeof(cases[0]); i++) {
    double got = te_call(cases[i].name, cases[i].args);
    double want = cases[i].want;
    double err = (want == 0.0) ? fabs(got) : fabs(got - want) / fabs(want);
    if (!(err <= cases[i].tol)) {
      failures++;
      printf("FAIL %-14s got=%.17g want=%.17g relerr=%.3g (tol %.0e)\n",
             cases[i].name, got, want, err, cases[i].tol);
    }
  }
  printf("%lu special-function checks, %d failures\n",
         sizeof(cases) / sizeof(cases[0]), failures);
  return failures > 0 ? 1 : 0;
}
