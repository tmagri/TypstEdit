    private func makeRecord(
        id: UUID = UUID(),
        title: String = "",
        titleIsAutoGenerated: Bool = true,
        messages: [ChatMessage],
        plan: [AgentPlanItem]? = nil,
        updatedAt: Date = Date(timeIntervalSince1970: 2_000)
    ) -> ChatSessionRecord {
        ChatSessionRecord(
            id: id,
            title: title,
            titleIsAutoGenerated: titleIsAutoGenerated,
            createdAt: Date(timeIntervalSince1970: 1_000),
            updatedAt: updatedAt,
            messages: messages,
            plan: plan
        )
    }

    // MARK: - Record Round Trip

    func testRecordRoundTripPreservesTranscript() throws {
        // Whole-second timestamps: the ISO8601 encoding drops sub-second
        // precision (same as the old history format), so the round trip is
        // only byte-equal for whole seconds.
        let stamp = Date(timeIntervalSince1970: 1_770_000_000)
        let messages = [
            ChatMessage(role: .user, text: "fix the table", timestamp: stamp),
            ChatMessage(role: .toolCall, timestamp: stamp, toolName: "project__read_file", toolStatus: .succeeded, toolOutput: "ok"),
            ChatMessage(role: .assistant, text: "done", timestamp: stamp, reasoning: "looked at it")
        ]
        let record = makeRecord(title: "Fix the table", titleIsAutoGenerated: false, messages: messages)

        let data = try AIChatSessionStore.encodeRecord(record)
        let decoded = try XCTUnwrap(AIChatSessionStore.decodeRecord(from: data))

        XCTAssertEqual(decoded, record)
        XCTAssertEqual(decoded.messages.map(\.role), [.user, .toolCall, .assistant])
        XCTAssertEqual(decoded.messages.first?.text, "fix the table")
        XCTAssertEqual(decoded.messages.last?.reasoning, "looked at it")
    }

    func testSessionIndexWithoutLabelsStillLoads() throws {
        let summary = ChatSessionSummary(
            id: UUID(),
            title: "Test",
            titleIsAutoGenerated: true,
            createdAt: Date(timeIntervalSince1970: 1_000),
            updatedAt: Date(timeIntervalSince1970: 2_000),
            messageCount: 1,
            labels: ["Research"]
        )
        let encoder = JSONEncoder()
        encoder.dateEncodingStrategy = .iso8601
        let encoded = try encoder.encode(summary)
        var object = try XCTUnwrap(JSONSerialization.jsonObject(with: encoded) as? [String: Any])
        object.removeValue(forKey: "labels")
        let oldIndexEntry = try JSONSerialization.data(withJSONObject: object)

        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        let decoded = try decoder.decode(ChatSessionSummary.self, from: oldIndexEntry)
        XCTAssertEqual(decoded.labels, [])
    }

    @MainActor
    func testHistorySearchAndLabelsUseTheSavedSessionIndex() async throws {
        let settings = AISettingsManager.shared
        let oldSavingSetting = settings.chatSessionsEnabled
        settings.chatSessionsEnabled = true
        let root = FileManager.default.temporaryDirectory
            .appendingPathComponent("typstedit-chat-search-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
        let store = AIChatSessionStore()
        defer {
            store.close()
            settings.chatSessionsEnabled = oldSavingSetting
            try? FileManager.default.removeItem(at: root)
        }
        store.updateContext(projectRoot: root, currentFileURL: nil)

        let record = makeRecord(
            title: "Thesis notes",
            messages: [ChatMessage(role: .user, text: "Find the rare citation phrase in this chapter.")]
        )
        let export = root.appendingPathComponent("conversation.json")
        try AIChatSessionStore.encodeRecord(record).write(to: export)
        let imported = try store.importSession(from: export)

        let matches = await store.searchSessions(query: "rare citation phrase")
        XCTAssertEqual(matches.map(\.id), [imported.id])
        XCTAssertTrue(matches.first?.snippet?.contains("rare citation phrase") == true)

        store.setLabels(["Thesis", " thesis ", "Research"], for: imported.id)
        XCTAssertEqual(store.sessions.first?.labels, ["Thesis", "Research"])
        let filtered = await store.searchSessions(query: "", label: "research")
        XCTAssertEqual(filtered.map(\.id), [imported.id])
        imported.persist()
        XCTAssertEqual(store.sessions.first?.labels, ["Thesis", "Research"])

        let labeledExport = root.appendingPathComponent("labeled-conversation.json")
        try store.exportSession(imported.id, to: labeledExport)
        let exportedRecord = try XCTUnwrap(AIChatSessionStore.decodeRecord(from: Data(contentsOf: labeledExport)))
        XCTAssertEqual(exportedRecord.labels, ["Thesis", "Research"])

        let importedAgain = try store.importSession(from: labeledExport)
        XCTAssertEqual(store.sessions.first(where: { $0.id == importedAgain.id })?.labels, ["Thesis", "Research"])
    }

