import XCTest
@testable import TypstEdit

/// The pure rules behind AI chat sessions: record encode/decode (including
/// the legacy `history.json` format and interrupted-tool repair), title
/// naming/indexing rules, and the scope→storage path layout.
@MainActor
final class ChatSessionStoreTests: XCTestCase {

    private func makeRecord(
        id: UUID = UUID(),
        title: String = "",
        titleIsAutoGenerated: Bool = true,
        messages: [ChatMessage],
        plan: [AgentPlanItem]? = nil
    ) -> ChatSessionRecord {
        ChatSessionRecord(
            id: id,
            title: title,
            titleIsAutoGenerated: titleIsAutoGenerated,
            createdAt: Date(timeIntervalSince1970: 1_000),
            updatedAt: Date(timeIntervalSince1970: 2_000),
            messages: messages,
            plan: plan
        )
    }

    // MARK: - Record Round Trip

    func testRecordRoundTripPreservesTranscript() throws {
        // Whole-second timestamps: the ISO8601 encoding drops sub-second
        // precision (same as the old history format), so the round trip is
        // only byte-equal for whole seconds.
        let stamp = Date(timeIntervalSince1970: 1_770_000_000)
        let messages = [
            ChatMessage(role: .user, text: "fix the table", timestamp: stamp),
            ChatMessage(role: .toolCall, timestamp: stamp, toolName: "project__read_file", toolStatus: .succeeded, toolOutput: "ok"),
            ChatMessage(role: .assistant, text: "done", timestamp: stamp, reasoning: "looked at it")
        ]
        let record = makeRecord(title: "Fix the table", titleIsAutoGenerated: false, messages: messages)

        let data = try AIChatSessionStore.encodeRecord(record)
        let decoded = try XCTUnwrap(AIChatSessionStore.decodeRecord(from: data))

        XCTAssertEqual(decoded, record)
        XCTAssertEqual(decoded.messages.map(\.role), [.user, .toolCall, .assistant])
        XCTAssertEqual(decoded.messages.first?.text, "fix the table")
        XCTAssertEqual(decoded.messages.last?.reasoning, "looked at it")
    }

    func testRecordRoundTripPreservesPlan() throws {
        let plan = [
            AgentPlanItem(content: "Map structure", status: .completed),
            AgentPlanItem(content: "Rewrite the section", status: .inProgress),
            AgentPlanItem(content: "Verify", status: .pending),
        ]
        let record = makeRecord(messages: [ChatMessage(role: .user, text: "do it")], plan: plan)

        let data = try AIChatSessionStore.encodeRecord(record)
        let decoded = try XCTUnwrap(AIChatSessionStore.decodeRecord(from: data))

        XCTAssertEqual(decoded.plan, plan)
    }

    @MainActor
    func testSuccessfulTurnFinalizesOpenPlanItems() {
        let planJSON = #"{"items":[{"content":"Read","status":"completed"},{"content":"Edit","status":"in_progress"},{"content":"Verify","status":"pending"}]}"#
        let chat = AIChatManager(messages: [
            ChatMessage(role: .toolCall, toolName: "agent__update_plan", toolArgumentsJSON: planJSON, toolStatus: .succeeded)
        ])
        XCTAssertEqual(chat.plan.map(\.status), [.completed, .inProgress, .pending])

        chat.finalizePlanAfterSuccessfulTurn()

        XCTAssertEqual(chat.plan.map(\.status), [.completed, .completed, .completed])
    }

    @MainActor
    func testFinalizingAnAlreadyFinishedPlanLeavesItAlone() {
        let planJSON = #"{"items":[{"content":"Read","status":"completed"},{"content":"Edit","status":"completed"}]}"#
        let chat = AIChatManager(messages: [
            ChatMessage(role: .toolCall, toolName: "agent__update_plan", toolArgumentsJSON: planJSON, toolStatus: .succeeded)
        ])
        let before = chat.plan

        chat.finalizePlanAfterSuccessfulTurn()

        XCTAssertEqual(chat.plan, before)
    }

    @MainActor
    func testLoadedRecordPrefersSavedPlanOverTranscriptRows() {
        let planJSON = #"{"items":[{"content":"Read","status":"in_progress"},{"content":"Verify","status":"pending"}]}"#
        let record = makeRecord(
            messages: [
                ChatMessage(role: .toolCall, toolName: "agent__update_plan", toolArgumentsJSON: planJSON, toolStatus: .succeeded)
            ],
            plan: [
                AgentPlanItem(content: "Read", status: .completed),
                AgentPlanItem(content: "Verify", status: .completed),
            ]
        )

        let chat = AIChatManager(record: record, scope: .none)

        XCTAssertEqual(chat.plan.map(\.status), [.completed, .completed])
    }

    @MainActor
    func testLoadedRecordWithoutAPlanRebuildsItFromTheTranscript() {
        let planJSON = #"{"items":[{"content":"Read","status":"completed"},{"content":"Verify","status":"in_progress"}]}"#
        let record = makeRecord(messages: [
            ChatMessage(role: .toolCall, toolName: "agent__update_plan", toolArgumentsJSON: planJSON, toolStatus: .succeeded)
        ])

        let chat = AIChatManager(record: record, scope: .none)

        XCTAssertEqual(chat.plan.map(\.status), [.completed, .inProgress])
    }

    func testDecodeRecordRepairsInterruptedToolRow() throws {
        let record = makeRecord(messages: [
            ChatMessage(role: .user, text: "hi"),
            ChatMessage(role: .toolCall, toolName: "project__grep_project", toolStatus: .running)
        ])
        let data = try AIChatSessionStore.encodeRecord(record)

        let decoded = try XCTUnwrap(AIChatSessionStore.decodeRecord(from: data))
        XCTAssertEqual(decoded.messages.last?.toolStatus, .cancelled)
        XCTAssertNotNil(decoded.messages.last?.toolOutput)
    }

    func testNormalizeLeavesFinishedRowsAlone() {
        let messages = [
            ChatMessage(role: .toolCall, toolName: "project__read_file", toolStatus: .succeeded, toolOutput: "ok"),
            ChatMessage(role: .toolCall, toolName: "project__read_file", toolStatus: .denied)
        ]
        XCTAssertEqual(AIChatSessionStore.normalize(messages), messages)
    }

    // MARK: - Legacy History Format

    func testLegacyHistoryImportsAsRecord() throws {
        // The exact format the old single-history persistence wrote.
        let legacy: [ChatMessage] = [
            ChatMessage(role: .user, text: "what does this project do?"),
            ChatMessage(role: .assistant, text: "It's a Typst editor.")
        ]
        let encoder = JSONEncoder()
        encoder.dateEncodingStrategy = .iso8601
        let data = try encoder.encode(legacy)

        let record = try XCTUnwrap(AIChatSessionStore.importRecord(from: data))
        XCTAssertEqual(record.messages.count, 2)
        XCTAssertEqual(record.title, "what does this project do?")
        XCTAssertTrue(record.titleIsAutoGenerated)
    }

    func testLegacyHistoryWithRunningToolStillImports() throws {
        let legacy: [ChatMessage] = [
            ChatMessage(role: .user, text: "go"),
            ChatMessage(role: .toolCall, toolName: "project__list_files", toolStatus: .running)
        ]
        let encoder = JSONEncoder()
        encoder.dateEncodingStrategy = .iso8601
        let data = try encoder.encode(legacy)

        let record = try XCTUnwrap(AIChatSessionStore.importRecord(from: data))
        XCTAssertEqual(record.messages.last?.toolStatus, .cancelled)
    }

    func testImportRejectsUnrelatedJSON() throws {
        let data = try JSONSerialization.data(withJSONObject: ["nope": 1])
        XCTAssertNil(AIChatSessionStore.importRecord(from: data))
        XCTAssertNil(AIChatSessionStore.importRecord(from: Data("not json".utf8)))
    }

    // MARK: - Titles

    func testSanitizedTitleFlattensWhitespaceAndCapsLength() {
        XCTAssertEqual(AIChatSessionStore.sanitizedTitle("  fix   the\nbroken   table  "), "fix the broken table")
        let long = AIChatSessionStore.sanitizedTitle(String(repeating: "word ", count: 30))
        XCTAssertLessThanOrEqual(long.count, 48)
        XCTAssertTrue(long.hasPrefix("word"))
        XCTAssertEqual(AIChatSessionStore.sanitizedTitle("   "), "")
    }

    func testFallbackTitleUsesFirstUserMessageOnly() {
        let messages = [
            ChatMessage(role: .assistant, text: "hello! how can I help?"),
            ChatMessage(role: .user, text: "restructure chapter two\n\nplease"),
        ]
        XCTAssertEqual(AIChatSessionStore.fallbackTitle(from: messages), "restructure chapter two please")
        XCTAssertEqual(AIChatSessionStore.fallbackTitle(from: []), "")
    }

    func testExportFileNameDropsUnsafeCharacters() {
        XCTAssertEqual(AIChatSessionStore.exportFileName(from: "Thesis: results & tables!"), "Thesis results tables")
        XCTAssertEqual(AIChatSessionStore.exportFileName(from: "   "), "chat")
        XCTAssertEqual(AIChatSessionStore.exportFileName(from: "a/b\\c"), "abc")
    }

    // MARK: - Indexing Rule

    func testEmptyUnnamedChatsAreNotIndexed() {
        XCTAssertFalse(AIChatSessionStore.shouldIndex(messageCount: 0, hasCustomTitle: false))
        XCTAssertTrue(AIChatSessionStore.shouldIndex(messageCount: 1, hasCustomTitle: false))
        // A renamed empty chat is worth keeping even without messages.
        XCTAssertTrue(AIChatSessionStore.shouldIndex(messageCount: 0, hasCustomTitle: true))
    }

    func testSummaryDisplayTitle() {
        var summary = ChatSessionSummary(
            id: UUID(), title: "", titleIsAutoGenerated: true,
            createdAt: Date(), updatedAt: Date(), messageCount: 0
        )
        XCTAssertEqual(summary.displayTitle, "Untitled chat")
        summary.title = "Tables"
        XCTAssertEqual(summary.displayTitle, "Tables")
    }

    // MARK: - Storage Layout

    func testSessionsDirectoryPerScope() {
        let projectRoot = URL(fileURLWithPath: "/tmp/project", isDirectory: true)
        let projectDir = AIChatSessionStore.sessionsDirectory(for: .project(root: projectRoot))
        XCTAssertEqual(
            projectDir?.path,
            ProjectSettingsManager.dotFolderURL(for: projectRoot)
                .appendingPathComponent("chat/sessions", isDirectory: true).path
        )

        let notebookRoot = URL(fileURLWithPath: "/tmp/notebook", isDirectory: true)
        let notebookDir = AIChatSessionStore.sessionsDirectory(for: .notebook(root: notebookRoot))
        XCTAssertNotNil(notebookDir)
        XCTAssertTrue(notebookDir?.path.contains("ChatHistory") ?? false)
        XCTAssertTrue(notebookDir?.path.hasSuffix("sessions") ?? false)

        XCTAssertNil(AIChatSessionStore.sessionsDirectory(for: .none))
    }

    func testLegacyTranscriptURLPerScope() {
        let projectRoot = URL(fileURLWithPath: "/tmp/project", isDirectory: true)
        let legacy = AIChatSessionStore.legacyTranscriptURL(for: .project(root: projectRoot))
        XCTAssertEqual(
            legacy?.path,
            ProjectSettingsManager.dotFolderURL(for: projectRoot)
                .appendingPathComponent("chat/history.json", isDirectory: false).path
        )
        XCTAssertNil(AIChatSessionStore.legacyTranscriptURL(for: .none))
    }

    func testRecordURLUsesSessionID() {
        let directory = URL(fileURLWithPath: "/tmp/sessions", isDirectory: true)
        let id = UUID()
        XCTAssertEqual(
            AIChatSessionStore.recordURL(in: directory, id: id),
            directory.appendingPathComponent(id.uuidString + ".json")
        )
        XCTAssertEqual(AIChatSessionStore.indexURL(in: directory), directory.appendingPathComponent("index.json"))
    }

    // MARK: - Record/Summary Bridge

    func testSummaryMirrorsRecord() {
        let messages = [ChatMessage(role: .user, text: "one"), ChatMessage(role: .assistant, text: "two")]
        let record = makeRecord(title: "My chat", titleIsAutoGenerated: false, messages: messages)
        let summary = ChatSessionSummary(record: record)

        XCTAssertEqual(summary.id, record.id)
        XCTAssertEqual(summary.title, "My chat")
        XCTAssertFalse(summary.titleIsAutoGenerated)
        XCTAssertEqual(summary.createdAt, record.createdAt)
        XCTAssertEqual(summary.updatedAt, record.updatedAt)
        XCTAssertEqual(summary.messageCount, 2)
    }
}
