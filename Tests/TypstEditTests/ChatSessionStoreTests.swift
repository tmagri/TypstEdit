    // MARK: - Record/Summary Bridge

    /// Writes `records` as a saved session store for `root`, newest listed
    /// first, so `updateContext` finds them the way a returning user would.
    private func seedSessions(_ records: [ChatSessionRecord], in root: URL) throws {
        let directory = try XCTUnwrap(
            AIChatSessionStore.sessionsDirectory(for: .project(root: root)))
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        for record in records {
            try AIChatSessionStore.encodeRecord(record)
                .write(to: AIChatSessionStore.recordURL(in: directory, id: record.id), options: .atomic)
        }
        let summaries = records
            .map(ChatSessionSummary.init(record:))
            .sorted { $0.updatedAt > $1.updatedAt }
        let encoder = JSONEncoder()
        encoder.dateEncodingStrategy = .iso8601
        try encoder.encode(summaries)
            .write(to: AIChatSessionStore.indexURL(in: directory), options: .atomic)
    }

    /// Switching between saved conversations must not keep every transcript
    /// resident: only the conversation on screen (and any still working) stays
    /// loaded, and coming back reads the others from disk again.
    @MainActor
    func testSwitchingSessionsUnloadsIdleTranscripts() throws {
        let root = FileManager.default.temporaryDirectory
            .appendingPathComponent("ChatSessionStoreTests-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: root) }

        let first = makeRecord(title: "First", messages: [ChatMessage(role: .user, text: "first chat")])
        let second = makeRecord(
            title: "Second",
            messages: [ChatMessage(role: .user, text: "second chat")],
            updatedAt: Date(timeIntervalSince1970: 3_000))
        try seedSessions([first, second], in: root)

        let store = AIChatSessionStore(context: ProjectContext())
        store.updateContext(projectRoot: root, currentFileURL: nil)

        // Newest is shown; the older transcript is saved but not resident.
        XCTAssertEqual(store.activeSessionID, second.id)
        XCTAssertEqual(store.activeManager.messages.map(\.text), ["second chat"])
        XCTAssertNil(store.manager(for: first.id))

        // Going back loads it again, transcript intact.
        store.switchSession(to: first.id)
        let reloaded = try XCTUnwrap(store.manager(for: first.id))
        XCTAssertEqual(reloaded.messages.map(\.text), ["first chat"])
        XCTAssertNil(store.manager(for: second.id), "the chat left behind is unloaded too")
    }

    /// A draft exists only in memory, so a chat holding one is never unloaded —
    /// switching away and back must not lose half-written text.
    @MainActor
    func testSessionWithAnUnsavedDraftIsNotUnloaded() throws {
        let root = FileManager.default.temporaryDirectory
            .appendingPathComponent("ChatSessionStoreTests-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: root) }

        let first = makeRecord(title: "First", messages: [ChatMessage(role: .user, text: "first chat")])
        let second = makeRecord(
            title: "Second",
            messages: [ChatMessage(role: .user, text: "second chat")],
            updatedAt: Date(timeIntervalSince1970: 3_000))
        try seedSessions([first, second], in: root)

        let store = AIChatSessionStore(context: ProjectContext())
        store.updateContext(projectRoot: root, currentFileURL: nil)
        store.switchSession(to: first.id)
        store.activeManager.draft = "half-written"

        store.startNewSession()
        XCTAssertNotNil(store.manager(for: first.id), "an unsaved draft pins the manager")

        store.switchSession(to: first.id)
        XCTAssertEqual(store.activeManager.draft, "half-written")
    }

